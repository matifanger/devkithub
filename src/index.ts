// Load settings from file
function loadSettings() {
  try {
    if (fs.existsSync(SETTINGS_FILE)) {
      const data = fs.readFileSync(SETTINGS_FILE, "utf8");
      let settings: Record<string, string> = {};
      try {
        settings = JSON.parse(data);
      } catch (error) {
        console.warn("Invalid JSON in settings file:", error);
        return;
      }
      Object.assign(persistentStore, settings);
      console.log("Settings loaded from", SETTINGS_FILE);
    }
  } catch (error) {
    console.error("Failed to load settings:", error);
  }
}

// Save settings to file
function saveSettings() {
  try {
    fs.writeFileSync(SETTINGS_FILE, JSON.stringify(persistentStore), "utf8");
    console.log("Settings saved to", SETTINGS_FILE);
  } catch (error) {
    console.error("Failed to save settings:", error);
  }
}

const createWindow = (): void => {
  // Create the browser window.
  const startHidden = shouldStartHidden(
    () => persistentStore[LAUNCH_ON_STARTUP_KEY] || null,
  );
  const mainWindow = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 650,
    minHeight: 650,
    frame: false,
    titleBarStyle: "hidden",
    show: !startHidden,
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      nodeIntegration: true, // Deshabilitado por seguridad
      contextIsolation: true, // Asegura el aislamiento de contexto
      sandbox: false,
      devTools: app.isPackaged ? false : true,
    },
  });

  if (app.isPackaged) {
    Menu.setApplicationMenu(null);
  }

  // Set CSP headers
  mainWindow.webContents.session.webRequest.onHeadersReceived(
    async (details, callback) => {
      callback({
        responseHeaders: {
          ...details.responseHeaders,
          "Content-Security-Policy": [
            "default-src 'self';",
            "script-src 'self' 'unsafe-inline' 'unsafe-eval';", // unsafe-eval needed for CodeMirror
            "style-src 'self' 'unsafe-inline';",
            "img-src 'self' data: blob:;",
            `connect-src 'self' ${await getBaseApiUrl()} https://www.google.com https://speech.googleapis.com https://huggingface.co https://cdn-lfs.huggingface.co https://cdn-lfs-us-1.hf.co https://github.com https://objects.githubusercontent.com;`,
            "worker-src 'self' blob:;",
            "media-src 'self' static: blob: data: mediastream:;",
          ].join(" "),
        },
      });
    },
  );

  // Handle new windows (middle-click, ctrl+click, etc.)
  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    console.log("Opening new window for URL:", url);

    // Use the default session - this should share resources properly
    const newWindow = new BrowserWindow({
      width: 1440,
      height: 900,
      frame: true,
      show: false,
      webPreferences: {
        preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
        nodeIntegration: false,
        contextIsolation: true,
        sandbox: false,
      },
    });

    // Add query param to indicate standalone window mode
    const urlWithMode = url.includes("?")
      ? `${url}&standalone=true`
      : `${url}?standalone=true`;

    // Log any errors in the new window
    newWindow.webContents.on(
      "did-fail-load",
      (event, errorCode, errorDescription) => {
        console.error(
          "New window failed to load:",
          errorCode,
          errorDescription,
        );
      },
    );

    newWindow.webContents.on("render-process-gone", (event, details) => {
      console.error("Render process gone in new window:", details);
    });

    // Show window when ready to prevent visual glitches
    newWindow.once("ready-to-show", () => {
      newWindow.show();
    });

    // Use same CSP as main window
    // Skip custom CSP for new windows - let main window handle it

    console.log("Loading URL in new window:", url);

    // Extract hash route from URL and load base app URL with route
    const urlObj = new URL(url);
    const hashRoute = urlObj.hash;
    const baseUrl = `${urlObj.protocol}//${urlObj.host}${urlObj.pathname}`;
    const hashPart = hashRoute ? `#${hashRoute.replace("#", "")}` : "";
    const fullUrl = `${baseUrl}${hashPart}?standalone=true`;

    console.log("Loading processed URL in new window:", fullUrl);

    // Load the app with the route
    newWindow.loadURL(fullUrl);

    return { action: "deny" };
  });

  // and load the index.html of the app.
  mainWindow.loadURL(MAIN_WINDOW_WEBPACK_ENTRY);

  // Keep a reference for later actions
  mainWindowRef = mainWindow;
  // setMainWindowRef(mainWindow);

  attachCloseBehavior(
    mainWindow,
    () => persistentStore["close-to-tray"] || null,
    (v) => {
      isQuitting = v;
    },
    () => isQuitting,
  );

  // Open DevTools only in development and only when visible
  if (!app.isPackaged && !startHidden) {
    mainWindow.webContents.openDevTools();
  }
};

// Set up IPC handlers for secure storage
function setupSecureStore() {
  ipcMain.handle("get-secure-store", async (_, key: string) => {
    try {
      return await keytar.getPassword(SERVICE_NAME, ACCOUNT_NAME);
    } catch (error) {
      console.error("Failed to retrieve from secure store:", error);
      return null;
    }
  });

  ipcMain.handle("set-secure-store", async (_, key: string, value: string) => {
    try {
      await keytar.setPassword(SERVICE_NAME, ACCOUNT_NAME, value);
      return true;
    } catch (error) {
      console.error("Failed to store securely:", error);
      return false;
    }
  });

  ipcMain.handle("delete-secure-store", async (_, key: string) => {
    try {
      await keytar.deletePassword(SERVICE_NAME, ACCOUNT_NAME);
      return true;
    } catch (error) {
      console.error("Failed to delete from secure store:", error);
      return false;
    }
  });

  // Add store handlers for general settings
  ipcMain.handle("get-store", async (_, key: string) => {
    try {
      return persistentStore[key] || null;
    } catch (error) {
      console.error(`Failed to get ${key} from store:`, error);
      return null;
    }
  });

  ipcMain.handle("set-store", async (_, key: string, value: string) => {
    try {
      persistentStore[key] = value;
      saveSettings();
      if (key === LAUNCH_ON_STARTUP_KEY) {
        applyAutostart(value === "true");
      }
      if (
        key === VOICE_TRANSCRIPTION_ENABLED_KEY ||
        key === VOICE_TRANSCRIPTION_SHORTCUT_KEY
      ) {
        registerVoiceShortcut();
      }
      if (key === VOICE_GOOGLE_API_KEY) {
        if (value) {
          process.env.GOOGLE_API_KEY = value;
        } else {
          delete process.env.GOOGLE_API_KEY;
        }
      }
      return true;
    } catch (error) {
      console.error(`Failed to set ${key} in store:`, error);
      return false;
    }
  });

  ipcMain.handle("delete-store", async (_, key: string) => {
    try {
      delete persistentStore[key];
      saveSettings();
      return true;
    } catch (error) {
      console.error(`Failed to delete ${key} from store:`, error);
      return false;
    }
  });

  // Add env handler
  ipcMain.handle("get-env", async (_, key: string) => {
    if (key === "npm_package_version") {
      return app.getVersion();
    }
    return process.env[key] || "";
  });

  ipcMain.handle("getHardwareInfo", async () => {
    return await getHardwareInfo();
  });

  ipcMain.handle("getSimpleHwid", () => {
    return getSimpleHwid();
  });

  ipcMain.handle("isPackaged", () => {
    return app.isPackaged;
  });

  // Window control handlers
  ipcMain.handle("window-minimize", (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    win?.minimize();
  });

  ipcMain.handle("window-maximize", (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    if (win?.isMaximized()) {
      win.unmaximize();
    } else {
      win?.maximize();
    }
  });

  ipcMain.handle("window-close", (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    win?.close();
  });

  ipcMain.handle("window-is-maximized", (event) => {
    const win = BrowserWindow.fromWebContents(event.sender);
    return win?.isMaximized() ?? false;
  });

  ipcMain.handle("figlet", async (_, text: string, font: string) => {
    try {
      const result = await figlet.text(text, {
        font: font || "Standard",
        horizontalLayout: "default",
        verticalLayout: "default",
      });
      return result;
    } catch (err) {
      console.error("Figlet error:", err);
      return text;
    }
  });

  ipcMain.handle("clipboard-read-text", () => {
    try {
      return clipboard.readText();
    } catch {
      return "";
    }
  });

  registerCloseDialogIpc(
    (value) => {
      persistentStore["close-to-tray"] = value;
      saveSettings();
    },
    () => mainWindowRef,
    (v) => {
      isQuitting = v;
    },
  );

  registerAutostartIpc(
    (value) => {
      persistentStore[LAUNCH_ON_STARTUP_KEY] = value;
      saveSettings();
    },
    (openAtLogin) => applyAutostart(openAtLogin),
  );
}

let currentVoiceShortcut: string | null = null;
let voiceWindow: BrowserWindow | null = null;

function openVoiceWindow() {
  if (voiceWindow && !voiceWindow.isDestroyed()) {
    voiceWindow.show();
    voiceWindow.focus();
    return;
  }

  voiceWindow = new BrowserWindow({
    width: 600,
    height: 700,
    minWidth: 400,
    minHeight: 400,
    frame: true,
    title: "Voice Transcription",
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      nodeIntegration: true,
      contextIsolation: true,
      sandbox: false,
    },
  });

  const baseUrl = MAIN_WINDOW_WEBPACK_ENTRY;
  const separator = baseUrl.includes("?") ? "&" : "?";
  voiceWindow.loadURL(`${baseUrl}${separator}standalone=true#/voice-transcription`);

  voiceWindow.on("closed", () => {
    voiceWindow = null;
  });
}

function registerVoiceShortcut(): { success: boolean; error?: string } {
  if (currentVoiceShortcut) {
    try {
      globalShortcut.unregister(currentVoiceShortcut);
    } catch {}
    currentVoiceShortcut = null;
  }

  const enabled = persistentStore[VOICE_TRANSCRIPTION_ENABLED_KEY];
  if (enabled !== "true") return { success: true };

  const shortcut =
    persistentStore[VOICE_TRANSCRIPTION_SHORTCUT_KEY] ||
    "CommandOrControl+Shift+V";

  try {
    const registered = globalShortcut.register(shortcut, () => {
      openVoiceWindow();
    });
    if (registered) {
      currentVoiceShortcut = shortcut;
      return { success: true };
    }
    return { success: false, error: `Shortcut "${shortcut}" is already in use by another application.` };
  } catch (err) {
    console.error("Failed to register voice shortcut:", err);
    return { success: false, error: err instanceof Error ? err.message : "Invalid shortcut format." };
  }
}

function setupVoiceShortcutIpc() {
  ipcMain.handle("register-voice-shortcut", () => {
    return registerVoiceShortcut();
  });

  ipcMain.handle("unregister-voice-shortcut", () => {
    if (currentVoiceShortcut) {
      try {
        globalShortcut.unregister(currentVoiceShortcut);
      } catch {}
      currentVoiceShortcut = null;
    }
    return { success: true };
  });

  ipcMain.handle("voice:get-config", () => {
    return {
      mode: persistentStore[VOICE_TRANSCRIPTION_MODE_KEY] || "google",
      model: persistentStore[VOICE_WHISPER_MODEL_KEY] || "ggml-tiny",
      googleApiKey: persistentStore[VOICE_GOOGLE_API_KEY] || "",
    };
  });

  ipcMain.handle("voice:get-status", (_, modelName: string) => {
    return whisperManager.getStatus(modelName);
  });

  ipcMain.handle("voice:download-model", async (event, modelName: string) => {
    try {
      await whisperManager.downloadModel(modelName, (progress) => {
        event.sender.send("voice:model-progress", progress);
      });
      return { success: true };
    } catch (err: any) {
      return { success: false, error: err?.message || "Download failed" };
    }
  });

  ipcMain.handle("voice:start-local-session", (_, sessionId: string, modelName: string, language?: string, translate?: boolean) => {
    return whisperManager.startSession(sessionId, modelName, language, translate);
  });

  ipcMain.handle("voice:push-audio-chunk", async (event, sessionId: string, audioData: ArrayBuffer) => {
    const result = await whisperManager.pushChunk(sessionId, Buffer.from(audioData));
    if (result) {
      event.sender.send("voice:transcript", {
        sessionId,
        text: result.text,
        error: result.error,
      });
    }
    return result;
  });

  ipcMain.handle("voice:stop-local-session", (_, sessionId: string) => {
    whisperManager.stopSession(sessionId);
    return { success: true };
  });
}

function setupInAppUpdaterIpc() {
  ipcMain.handle(
    "download-and-install-update",
    async (_, downloadUrl: string) => {
      try {
        const tempDir = path.join(app.getPath("temp"), "devkithub-update");
        if (!fs.existsSync(tempDir)) {
          fs.mkdirSync(tempDir, { recursive: true });
        }

        const fileName = path.basename(new URL(downloadUrl).pathname) || "update-installer.exe";
        const filePath = path.join(tempDir, fileName);

        if (mainWindowRef) {
          mainWindowRef.webContents.send("update-download-progress", {
            status: "downloading",
            percent: 0,
          });
        }

        const https = require("https");
        const http = require("http");
        const client = downloadUrl.startsWith("https") ? https : http;

        await new Promise<void>((resolve, reject) => {
          const file = fs.createWriteStream(filePath);
          client
            .get(downloadUrl, (response: any) => {
              if (response.statusCode === 302 || response.statusCode === 301) {
                client
                  .get(response.headers.location, (redirected: any) => {
                    const totalBytes = parseInt(
                      redirected.headers["content-length"] || "0",
                      10,
                    );
                    let downloaded = 0;

                    redirected.on("data", (chunk: Buffer) => {
                      downloaded += chunk.length;
                      if (totalBytes > 0 && mainWindowRef) {
                        mainWindowRef.webContents.send(
                          "update-download-progress",
                          {
                            status: "downloading",
                            percent: Math.round(
                              (downloaded / totalBytes) * 100,
                            ),
                          },
                        );
                      }
                    });
                    redirected.pipe(file);
                    file.on("finish", () => {
                      file.close();
                      resolve();
                    });
                  })
                  .on("error", reject);
                return;
              }

              const totalBytes = parseInt(
                response.headers["content-length"] || "0",
                10,
              );
              let downloaded = 0;

              response.on("data", (chunk: Buffer) => {
                downloaded += chunk.length;
                if (totalBytes > 0 && mainWindowRef) {
                  mainWindowRef.webContents.send(
                    "update-download-progress",
                    {
                      status: "downloading",
                      percent: Math.round((downloaded / totalBytes) * 100),
                    },
                  );
                }
              });
              response.pipe(file);
              file.on("finish", () => {
                file.close();
                resolve();
              });
            })
            .on("error", reject);
        });

        if (mainWindowRef) {
          mainWindowRef.webContents.send("update-download-progress", {
            status: "installing",
            percent: 100,
          });
        }

        const { exec } = require("child_process");
        exec(`"${filePath}"`, (err: any) => {
          if (!err) {
            app.quit();
          }
        });

        return { success: true, filePath };
      } catch (err: any) {
        console.error("Update download failed:", err);
        return { success: false, error: err.message };
      }
    },
  );
}

